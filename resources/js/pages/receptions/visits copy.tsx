const NUMERIC_STATUS: Record<number, VisitStatus> = {
    0: 'cancelled',
    1: 'active',
    2: 'pending',
    3: 'in_progress',
    4: 'completed',
};

const VALID_STATUSES: VisitStatus[] = [
    'pending',
    'active',
    'in_progress',
    'completed',
    'cancelled',
];

const normalizeStatus = (
    status: number | string | null | undefined,
): VisitStatus => {
    if (status === null || status === undefined || status === '') {
        return 'pending';
    }
    if (typeof status === 'number') {
        return NUMERIC_STATUS[status] ?? 'pending';
    }
    const key = status.toLowerCase().replace(/[\s-]+/g, '_') as VisitStatus;
    return VALID_STATUSES.includes(key) ? key : 'pending';
};

const capitalize = (value: string): string =>
    value ? value.charAt(0).toUpperCase() + value.slice(1).toLowerCase() : '';

/**
 * Backend timestamps look like "2026-04-24 18:19:46". Safari cannot parse the
 * space-separated form, so swap it for the ISO "T".
 */
const parseDate = (value?: string | null): Date | null => {
    if (!value) return null;
    const date = new Date(value.replace(' ', 'T'));
    return Number.isNaN(date.getTime()) ? null : date;
};

const formatDate = (value?: string | null): string => {
    const date = parseDate(value);
    return date
        ? date.toLocaleDateString('en-GB', {
              day: '2-digit',
              month: 'short',
              year: 'numeric',
          })
        : 'N/A';
};

const formatTime = (value?: string | null): string => {
    const date = parseDate(value);
    return date
        ? date.toLocaleTimeString('en-GB', {
              hour: '2-digit',
              minute: '2-digit',
          })
        : '';
};

const formatDateTime = (value?: string | null): string => {
    const date = parseDate(value);
    return date ? `${formatDate(value)}, ${formatTime(value)}` : 'N/A';
};

const normalizeRecord = (record: QueueRecord): QueuePatient => ({
    ...record,
    token: record.token || `T-${String(record.id).padStart(4, '0')}`,
    patient_number: record.patient_number || 'N/A',
    patient_name: record.patient_name?.trim() || 'Unknown patient',
    contact: record.contact || 'N/A',
    gender: record.gender ? capitalize(record.gender) : 'N/A',
    payment_method:
        record.payment_method ||
        record.original_payment_method ||
        'Not specified',
    // `visit_status` is already a string from the API; fall back to numeric `status`.
    visit_status: normalizeStatus(record.visit_status ?? record.status),
    priority: (record.priority || 'routine').toLowerCase(),
    assigned_department: record.assigned_department || 'Not assigned',
    assigned_staff: record.assigned_staff || 'Not assigned',
});

