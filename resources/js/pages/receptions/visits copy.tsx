export default function Nurses() {
    // Inertia shares controller data as page props: Inertia::render('...', ['queue' => ..., 'stats' => ...])
    const { queue = [] } = usePage<Props>().props;

    const [selectedPatient, setSelectedPatient] = useState<QueuePatient | null>(
        null,
    );
    const [showDetailsModal, setShowDetailsModal] = useState(false);
    const [loading, setLoading] = useState(false);

    // Normalised rows: this is what the table and the modal consume.
    const processedQueue = useMemo<QueuePatient[]>(
        () => queue.map(normalizeRecord),
        [queue],
    );

    // ------------------------------------------------------------------------
    // Handlers
    // ------------------------------------------------------------------------

    const handleViewDetails = (patient: QueuePatient) => {
        setSelectedPatient(patient);
        setShowDetailsModal(true);
    };

    const handleStatusUpdate = async (
        queueId: number,
        newStatus: VisitStatus,
    ) => {
        setLoading(true);
        Notiflix.Loading.pulse('Updating...');
        try {
            const response = await Http.post(
                `/nurses/queue/${queueId}/status`,
                { status: newStatus },
            );
            if (response.data.success) {
                Notiflix.Notify.success(
                    `Status updated to ${STATUS_CONFIG[newStatus].label}`,
                );
                router.reload({ only: ['queue', 'stats'] });
            } else {
                Notiflix.Notify.failure(
                    response.data.message || 'Failed to update status',
                );
            }
        } catch (error: any) {
            Notiflix.Notify.failure(
                error.response?.data?.message || 'Failed to update status',
            );
        } finally {
            Notiflix.Loading.remove();
            setLoading(false);
        }
    };

    // ------------------------------------------------------------------------
    // Columns
    // ------------------------------------------------------------------------

    const columns: Column<QueuePatient>[] = [
        {
            id: 'token',
            label: 'Token',
            sortable: true,
            format: (value) => (
                <span className="font-mono text-sm font-medium text-blue-600 dark:text-blue-400">
                    {value || 'N/A'}
                </span>
            ),
        },
        {
            id: 'patient_name',
            label: 'Patient',
            sortable: true,
            filterable: true,
            format: (_value, row) => (
                <Link
                    href={`/patients/dashboard/${row.patient_id}`}
                    className="flex items-center gap-2.5 hover:text-blue-600 dark:hover:text-blue-400"
                >
                    <PatientAvatar
                        name={row.patient_name}
                        patientId={row.patient_id}
                        gender={row.gender}
                        photoUrl={row.photo_url}
                    />
                    <div>
                        <span className="font-medium text-slate-800 dark:text-slate-200">
                            {row.patient_name}
                        </span>
                        <div className="flex items-center gap-2 text-xs text-slate-400">
                            <span>EMR #: {row.patient_number}</span>
                            {row.contact !== 'N/A' && (
                                <>
                                    <span>•</span>
                                    <Phone size={10} />
                                    <span>{row.contact}</span>
                                </>
                            )}
                        </div>
                    </div>
                </Link>
            ),
        },
        {
            id: 'priority',
            label: 'Priority',
            sortable: true,
            format: (_value, row) => <PriorityBadge priority={row.priority} />,
        },
        {
            id: 'visit_status',
            label: 'Status',
            sortable: true,
            filterable: true,
            format: (_value, row) => <StatusBadge status={row.visit_status} />,
        },
        {
            id: 'assigned_department',
            label: 'Department',
            sortable: true,
            format: (_value, row) => (
                <div className="flex items-center gap-1.5 text-sm text-slate-700 dark:text-slate-300">
                    <Building2 size={14} className="text-slate-400" />
                    {row.assigned_department}
                </div>
            ),
        },
        {
            id: 'registered_at',
            label: 'Arrived',
            sortable: true,
            format: (value) => (
                <div className="flex items-center gap-1.5">
                    <Clock size={14} className="text-slate-400" />
                    <span className="text-sm text-slate-700 dark:text-slate-300">
                        {formatDateTime(value as string)}
                    </span>
                </div>
            ),
        },
        {
            id: 'payment_method',
            label: 'Payment',
            sortable: true,
            format: (_value, row) => (
                <PaymentBadge method={row.payment_method} />
            ),
        },
    ];

    // ------------------------------------------------------------------------
    // Actions
    // ------------------------------------------------------------------------

    const actions: Action<QueuePatient>[] = [
        {
            label: 'View Dashboard',
            icon: <Eye size={16} />,
            color: 'info',
            onClick: (row) =>
                router.visit(`/patients/dashboard/${row.patient_id}`),
        },
        {
            label: 'Details',
            icon: <User size={16} />,
            color: 'info',
            onClick: (row) => handleViewDetails(row),
        },
    ];

    const statusOptions = VALID_STATUSES.map((value) => ({
        value,
        label: STATUS_CONFIG[value].label,
    }));

    // ------------------------------------------------------------------------
    // Render
    // ------------------------------------------------------------------------

    return (
        <AppLayout
            breadcrumbs={[
                { href: '/dashboard', title: 'Altaf Memorial Hospital' },
                { href: '', title: 'Department' },
                { href: '', title: 'Reception' },
            ]}
        >
            <PageHeader
                icon={<StethoscopeIcon />}
                title="Reception Encounter Queue"
                subtitle="View and manage patients currently in the queue"
            />
            <div className="flex h-full min-h-screen flex-1 flex-col gap-4 bg-blue-50 p-4 dark:bg-slate-900">
                <ReusableTable
                    columns={columns}
                    data={processedQueue}
                    actions={actions}
                    loading={loading}
                    filterPlaceholder="Search by patient name, token, or contact..."
                    statusFilterKey="visit_status"
                    statusOptions={statusOptions}
                    rowsPerPageOptions={[5, 10, 25, 50]}
                    defaultRowsPerPage={10}
                    defaultOrderBy="registered_at"
                    emptyMessage="No patients in the queue"
                    className="shadow-sm"
                />

                {/* Details Modal */}
                <Dialog
                    open={showDetailsModal}
                    onOpenChange={(open) => {
                        setShowDetailsModal(open);
                        if (!open) setSelectedPatient(null);
                    }}
                >
                    <DialogContent className="max-w-md">
                        <DialogHeader>
                            <DialogTitle className="text-sm">
                                Patient Details
                            </DialogTitle>
                        </DialogHeader>

                        {selectedPatient && (
                            <div className="space-y-4">
                                <div className="flex items-center gap-3">
                                    <PatientAvatar
                                        name={selectedPatient.patient_name}
                                        patientId={selectedPatient.patient_id}
                                        gender={selectedPatient.gender}
                                        photoUrl={selectedPatient.photo_url}
                                        size="lg"
                                    />
                                    <div>
                                        <p className="text-sm font-medium">
                                            {selectedPatient.patient_name}
                                        </p>
                                        <p className="text-xs text-slate-500">
                                            Token: {selectedPatient.token}
                                        </p>
                                    </div>
                                </div>

                                <div className="grid grid-cols-2 gap-3">
                                    <DetailField label="EMR number">
                                        {selectedPatient.patient_number}
                                    </DetailField>
                                    <DetailField label="Contact">
                                        {selectedPatient.contact}
                                    </DetailField>
                                    <DetailField label="Gender">
                                        {selectedPatient.gender}
                                    </DetailField>
                                    <DetailField label="Priority">
                                        <PriorityBadge
                                            priority={selectedPatient.priority}
                                        />
                                    </DetailField>
                                    <DetailField label="Status">
                                        <StatusBadge
                                            status={
                                                selectedPatient.visit_status
                                            }
                                        />
                                    </DetailField>
                                    <DetailField label="Payment">
                                        <PaymentBadge
                                            method={
                                                selectedPatient.payment_method
                                            }
                                        />
                                    </DetailField>
                                    <DetailField label="Department">
                                        {selectedPatient.assigned_department}
                                    </DetailField>
                                    <DetailField label="Assigned staff">
                                        {selectedPatient.assigned_staff}
                                    </DetailField>
                                    <DetailField label="Arrived">
                                        {formatDateTime(
                                            selectedPatient.registered_at,
                                        )}
                                    </DetailField>
                                </div>

                                <div className="flex items-center justify-between gap-2 border-t pt-3">
                                    <Link
                                        href={`/patients/dashboard/${selectedPatient.patient_id}`}
                                        className="inline-flex items-center gap-1 rounded bg-blue-50 px-3 py-1.5 text-xs font-medium text-blue-600 transition-colors hover:bg-blue-100 dark:bg-blue-950/30 dark:text-blue-400"
                                    >
                                        <Eye className="h-3.5 w-3.5" />
                                        Dashboard
                                    </Link>

                                    <div className="flex gap-2">
                                        {selectedPatient.visit_status ===
                                            'pending' && (
                                            <Button
                                                size="sm"
                                                className="text-xs"
                                                disabled={loading}
                                                onClick={async () => {
                                                    await handleStatusUpdate(
                                                        selectedPatient.id,
                                                        'active',
                                                    );
                                                    setShowDetailsModal(false);
                                                }}
                                            >
                                                {loading && (
                                                    <Loader2 className="mr-1 h-3.5 w-3.5 animate-spin" />
                                                )}
                                                Mark active
                                            </Button>
                                        )}
                                        <Button
                                            size="sm"
                                            variant="outline"
                                            className="text-xs"
                                            onClick={() =>
                                                setShowDetailsModal(false)
                                            }
                                        >
                                            Close
                                        </Button>
                                    </div>
                                </div>
                            </div>
                        )}
                    </DialogContent>
                </Dialog>
            </div>
        </AppLayout>
    );
}
