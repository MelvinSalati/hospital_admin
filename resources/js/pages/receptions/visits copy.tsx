type VisitStatus =
    | 'pending'
    | 'active'
    | 'in_progress'
    | 'completed'
    | 'cancelled';

/** Shape of one row exactly as the backend sends it. */
interface QueueRecord {
    id: number;
    token: string | null;
    visit_token_id?: number;
    patient_id: number;
    patient_number?: string | null;
    patient_name: string | null;
    contact: string | null;
    gender: string | null;
    payment_method: string | null;
    original_payment_method: string | null;
    status: number | string | null;
    registered_at: string | null;
    assigned_department: string | null;
    assigned_staff: string | null;
    visit_status: string | null;
    priority: string | null;
    department_id: number | null;
    /** Optional: a real photo URL from your backend. Wins over the illustrated avatar. */
    photo_url?: string | null;
}

/** Row after normalisation: every field the UI reads is guaranteed to be set. */
interface QueuePatient extends Omit<
    QueueRecord,
    | 'token'
    | 'patient_number'
    | 'patient_name'
    | 'contact'
    | 'gender'
    | 'payment_method'
    | 'visit_status'
    | 'priority'
    | 'assigned_department'
    | 'assigned_staff'
> {
    token: string;
    patient_number: string;
    patient_name: string;
    contact: string;
    gender: string;
    payment_method: string;
    visit_status: VisitStatus;
    priority: string;
    assigned_department: string;
    assigned_staff: string;
}

interface Stats {
    total_in_queue: number;
    pending_assignment: number;
    assigned_today: number;
}

interface Props {
    [key: string]: unknown;
    queue?: QueueRecord[];
    stats?: Stats;
}

